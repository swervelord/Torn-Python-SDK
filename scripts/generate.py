from __future__ import annotations

import argparse
import hashlib
import json
import keyword
import re
from collections import defaultdict
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "spec"
PACKAGE = ROOT / "src" / "torn_sdk"
HEADER = "# Generated by scripts/generate.py. Do not edit.\n"
Schema = dict[str, Any]


def read(path: str) -> Any:
    return json.loads((SPEC / path).read_bytes())


def snake(name: str) -> str:
    value = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    value = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", value)
    return re.sub(r"[^a-z0-9]+", "_", value.lower()).strip("_")


def field_name(key: str) -> str:
    name = snake(key)
    if not name or name[0].isdigit():
        name = f"field_{name}"
    if keyword.iskeyword(name) or name in {"copy", "dict", "json", "schema", "validate", "construct"}:
        return f"{name}_"
    if name.startswith("model_"):
        return f"wire_{name}"
    return name


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^A-Za-z0-9]+", name) if part)


def ref_name(schema: Schema) -> str:
    return schema["$ref"].rsplit("/", 1)[1]


def union(branches: list[str]) -> str:
    unique = list(dict.fromkeys(branches))
    if "None" in unique and len(unique) > 1:
        unique.remove("None")
        unique.append("None")
    return " | ".join(unique) or "JsonValue"


def tuple_source(values: list[str]) -> str:
    return "(" + ", ".join(values) + ("," if len(values) == 1 else "") + ")"


def enum_source(name: str, values: list[str | int]) -> str:
    base = "OpenEnum" if isinstance(values[0], str) else "OpenIntEnum"
    existing: set[str] = set()
    members = []
    for value in values:
        candidate = (snake(str(value)) or "EMPTY").upper()
        if candidate[0].isdigit() or candidate in {"NAME", "VALUE"}:
            candidate = f"VALUE_{candidate}"
        suffix = 2
        member = candidate
        while member in existing:
            member = f"{candidate}_{suffix}"
            suffix += 1
        existing.add(member)
        members.append(f"    {member} = {value!r}")
    return f"class {name}({base}):\n" + "\n".join(members)


