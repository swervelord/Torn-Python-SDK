class Models:
    def __init__(self, schemas: dict[str, Schema], overrides: dict[tuple[str, str], str]):
        self.schemas = schemas
        self.overrides = overrides
        self.classes: dict[str, str] = {}
        self.aliases: dict[str, str] = {}
        self.enums: dict[str, str] = {}

    def object_fields(self, schema: Schema) -> tuple[Schema, set[str]]:
        if "$ref" in schema:
            return self.object_fields(self.schemas[ref_name(schema)])
        properties: Schema = {}
        required: set[str] = set()
        for branch in schema.get("allOf", []):
            branch_properties, branch_required = self.object_fields(branch)
            properties.update(branch_properties)
            required.update(branch_required)
        properties.update(schema.get("properties", {}))
        required.update(schema.get("required", []))
        return properties, required

    def canonical_name(self, name: str, schema: Schema) -> str:
        if name not in self.schemas or schema == self.schemas[name]:
            return name
        suffix = 2
        while f"{name}{suffix}" in self.schemas:
            suffix += 1
        return f"{name}{suffix}"

    def object(self, name: str, schema: Schema) -> str:
        name = self.canonical_name(name, schema)
        if name in self.classes:
            return name
        self.classes[name] = ""
        properties, required = self.object_fields(schema)
        properties.update({key: {} for key in sorted(required - properties.keys())})
        lines = [f"class {name}(WireModel):"]
        relaxed = []
        used: set[str] = set()
        for key, field_schema in properties.items():
            attr = field_name(key)
            while attr in used:
                attr += "_"
            used.add(attr)
            change = self.overrides.get((name, key))
            is_required = key in required and change != "optional"
            field_type = self.type_of(field_schema, f"{name}{pascal(attr)}")
            if not is_required or change == "nullable":
                field_type = union([field_type, "None"])
            if change == "optional" and key in required:
                relaxed.append(key)
            arguments = ([] if is_required else ["default=None"]) + (
                [] if attr == key else [f"alias={key!r}"]
            )
            field_call = f" = Field({', '.join(arguments)})" if arguments else ""
            lines.append(f"    {attr}: {field_type}{field_call}")
        if relaxed:
            lines.append(f"    __relaxed_fields__ = {tuple(relaxed)!r}")
        if schema.get("additionalProperties") is not False and not properties:
            lines.append("    __accept_extra__ = True")
        if len(lines) == 1:
            lines.append("    pass")
        self.classes[name] = "\n".join(lines)
        return name

    def type_of(self, schema: Schema, name: str, *, params: bool = False) -> str:
        if "$ref" in schema:
            reference = ref_name(schema)
            if params:
                target = self.schemas[reference]
                if "enum" in target:
                    return union([f"Literal[{', '.join(repr(x) for x in target['enum'])}]", f"models.{reference}"])
            return f"models.{reference}" if params else reference
        for key in ("oneOf", "anyOf"):
            if key in schema:
                values = schema[key]
                if not params and len(values) == 2 and values[1] == {"type": "string"}:
                    if "$ref" in values[0] and "enum" in self.schemas[ref_name(values[0])]:
                        return ref_name(values[0])
                    if values[0].get("enum"):
                        self.enums.setdefault(name, enum_source(name, values[0]["enum"]))
                        return name
                return union([
                    self.type_of(branch, f"{name}Variant{index + 1}", params=params)
                    for index, branch in enumerate(values)
                ])
        if "enum" in schema:
            values = schema["enum"]
            if params:
                return f"Literal[{', '.join(repr(x) for x in values)}]"
            enum_name = self.canonical_name(name, schema)
            self.enums.setdefault(enum_name, enum_source(enum_name, values))
            return enum_name
        kind = schema.get("type")
        if isinstance(kind, dict):
            return self.type_of(kind, name, params=params)
        if isinstance(kind, list):
            return union([self.type_of({**schema, "type": x}, name, params=params) for x in kind])
        if "properties" in schema or "allOf" in schema:
            if params:
                raise ValueError(f"Inline object parameter needs dedicated generation: {name}")
            return self.object(name, schema)
        if kind == "object":
            additional = schema.get("additionalProperties")
            item = self.type_of(additional, f"{name}Value", params=params) if isinstance(additional, dict) else "JsonValue"
            return f"dict[str, {item}]"
        if kind == "array":
            item = self.type_of(schema.get("items", {}), f"{name}Item", params=params)
            if "prefixItems" in schema:
                return "tuple[" + ", ".join(
                    self.type_of(entry, f"{name}Item{index}", params=params)
                    for index, entry in enumerate(schema["prefixItems"])
                ) + "]"
            returns = f"list[{item}]"
        else:
            returns = {
                None: "JsonValue",
                "string": "str",
                "integer": "int",
                "boolean": "bool",
                "number": "float",
                "null": "None",
            }[kind]
        constraints = {
            parameter: schema[key]
            for key, parameter in {
                "minimum": "ge",
                "maximum": "le",
                "exclusiveMinimum": "gt",
                "exclusiveMaximum": "lt",
                "minLength": "min_length",
                "maxLength": "max_length",
                "minItems": "min_length",
                "maxItems": "max_length",
                "pattern": "pattern",
            }.items()
            if key in schema
        }
        if constraints:
            fields = ", ".join(f"{key}={value!r}" for key, value in constraints.items())
            return f"Annotated[{returns}, Field({fields})]"
        return returns

    def populate(self) -> None:
        for name, schema in self.schemas.items():
            target = self.type_of(schema, name)
            if target != name:
                self.aliases[name] = target

    def ordered_aliases(self) -> list[str]:
        aliases = dict(self.aliases)
        ordered = []
        while aliases:
            for name, expression in list(aliases.items()):
                if not re.search(r"\b(?:" + "|".join(aliases) + r")\b", expression):
                    ordered.append(f"{name}: TypeAlias = {expression}")
                    del aliases[name]
            if len(ordered) + len(aliases) != len(self.aliases):
                raise AssertionError("Lost alias during dependency sorting")
            if aliases and not any(
                not set(re.findall(r"\w+", expression)).intersection(aliases)
                for expression in aliases.values()
            ):
                raise ValueError(f"Cyclic aliases: {aliases}")
        return ordered

    def render(self, docstring: str, imports: str = MODEL_IMPORTS) -> str:
        sections = [f'{HEADER}"""{docstring}"""\n\n{imports.rstrip()}']
        sections.extend(self.enums.values())
        sections.extend(self.classes.values())
        sections.append("\n".join(self.ordered_aliases()))
        public_names = sorted(self.schemas)
        sections.append("__all__ = [\n" + "".join(f"    {name!r},\n" for name in public_names) + "]")
        return "\n\n\n".join(sections) + "\n"


class Compatibility(Models):
    def compat_type(self, schema: Schema) -> str:
        name = schema["name"]
        children = schema.get("arguments", [])
        if name == "optional":
            return union([self.compat_type(children[0]), "None"])
        if name == "box":
            return self.compat_type(children[0])
        if name == "array":
            return f"list[{self.compat_type(children[0])}]"
        if name == "map":
            return f"dict[{self.compat_type(children[0])}, {self.compat_type(children[1])}]"
        return {
            "raw": "JsonValue",
            "string": "str",
            "int64": "int",
            "uint64": "int",
            "uint32": "int",
            "float64": "float",
            "exact_number": "int | float",
            "null": "None",
        }.get(name, name)

    def populate(self) -> None:
        for name, schema in self.schemas.items():
            kind = schema["Kind"]
            if name == "DynamicValue":
                self.aliases[name] = "JsonValue"
            elif kind == "alias":
                self.aliases[name] = self.compat_type(schema["Type"])
            elif kind == "union":
                self.aliases[name] = union([self.compat_type(item) for item in schema["Variants"]])
            else:
                has_extra = any(field["Flatten"] for field in schema["Fields"])
                base = "CompatibilityModel" if has_extra else "WireModel"
                fields = [f"class {name}({base}):"]
                for entry in schema["Fields"]:
                    if entry["Flatten"]:
                        fields.append("    __accept_extra__ = True")
                        continue
                    key = entry["Key"]
                    attr = field_name(entry["Name"])
                    field_type = self.compat_type(entry["Type"])
                    aliases = list(entry["Aliases"])
                    if attr in {"job_type", "item_type"} and key != "type" and "type" not in aliases:
                        aliases.append("type")
                    arguments = []
                    if aliases:
                        choices = ", ".join(repr(choice) for choice in [key, *aliases])
                        arguments.append(f"validation_alias=AliasChoices({choices})")
                    if attr != key or aliases:
                        arguments.append(f"alias={key!r}")
                    if entry["Default"]:
                        if entry["Type"]["name"] in {"array", "map"}:
                            factory = "list" if entry["Type"]["name"] == "array" else "dict"
                            arguments.append(f"default_factory={factory}")
                        else:
                            field_type = union([field_type, "None"])
                            arguments.append("default=None")
                    if entry["Custom"]:
                        validator = {
                            "company_news": "company_news",
                            "optional_position_name": "position_name",
                            "optional_stringish": "stringish",
                        }[entry["Custom"]]
                        field_type = f"Annotated[{field_type}, BeforeValidator({validator})]"
                    suffix = f" = Field({', '.join(arguments)})" if arguments else ""
                    fields.append(f"    {attr}: {field_type}{suffix}")
                if len(fields) == 1:
                    fields.append("    pass")
                self.classes[name] = "\n".join(fields)


def resolve(nodes: dict[str, Schema], value: Schema) -> Schema:
    return nodes[ref_name(value)] if "$ref" in value else value


def cache_ttl(description: str) -> int | None:
    match = re.search(r"cach(?:ed|e)[^.\n]*?(\d+)\s*(seconds?|minutes?|hours?|days?)", description, re.I)
    if match:
        amount = int(match[1])
        unit = match[2].lower().rstrip("s")
        return amount * {"second": 1, "minute": 60, "hour": 3600, "day": 86400}[unit]
    return None


def metadata_shape(models: Models, schema: Schema) -> bool:
    schema = resolve(models.schemas, schema)
    for union_key in ("oneOf", "anyOf"):
        if union_key in schema:
            return any(metadata_shape(models, branch) for branch in schema[union_key])
    properties, _ = models.object_fields(schema)
    metadata = resolve(models.schemas, properties.get("_metadata", {}))
    return "links" in models.object_fields(metadata)[0]


def collection_shape(models: Models, schema: Schema, path: tuple[str, ...] = ()) -> tuple[tuple[str, ...], Schema] | None:
    schema = resolve(models.schemas, schema)
    for union_key in ("oneOf", "anyOf"):
        if union_key in schema:
            branches = [value for branch in schema[union_key] if (value := collection_shape(models, branch, path))]
            if not branches or len({branch[0] for branch in branches}) != 1:
                return None
            variants = [branch[1] for branch in branches]
            return branches[0][0], variants[0] if all(v == variants[0] for v in variants) else {"oneOf": variants}
    if schema.get("type") == "array":
        return path, schema["items"]
    if isinstance(schema.get("additionalProperties"), dict):
        return path, schema["additionalProperties"]
    props, _ = models.object_fields(schema)
    for key, child in props.items():
        if key != "_metadata" and (result := collection_shape(models, child, (*path, key))):
            return result
    return None


class Operations:
    def __init__(self, spec: Schema, models: Models, access: Schema):
        self.models = models
        self.entries: dict[str, Schema] = {}
        for route, path in spec["paths"].items():
            operation = path["get"]
            op_id = operation["operationId"]
            class_prefix = pascal(op_id)
            selection = operation["responses"]["200"]["content"]
            media, data = next(iter(selection.items()))
            response_schema = data["schema"]
            response = models.type_of(response_schema, f"{class_prefix}Response")
            if response != f"{class_prefix}Response" and "$ref" not in response_schema and media != "text/csv":
                models.aliases[f"{class_prefix}Response"] = response
                response = f"{class_prefix}Response"
            paginated = (
                media != "text/csv"
                and route.count("/") > 1
                and metadata_shape(models, response_schema)
            )
            items = collection_shape(models, response_schema) if paginated else None
            item_path, item_type = items if items else (None, None)
            if item_type is not None:
                typed_item = models.type_of(item_type, f"{class_prefix}Item")
                if not typed_item.isidentifier():
                    models.aliases[f"{class_prefix}Item"] = typed_item
                    typed_item = f"{class_prefix}Item"
            else:
                typed_item = None
            parameters = [
                resolve(spec["components"]["parameters"], parameter)
                for parameter in operation.get("parameters", [])
            ]
            parameters = [parameter for parameter in parameters if parameter["name"] != "key"]
            self.entries[op_id] = {
                "reference": snake(op_id),
                "params": f"{class_prefix}Params",
                "parameters": parameters,
                "required": any(parameter.get("required") for parameter in parameters),
                "response": response,
                "path": route,
                "access": access[op_id]["access"],
                "cache_ttl": cache_ttl(operation.get("description", "")),
                "paginated": paginated,
                "media": media,
                "summary": operation.get("summary", "").strip(),
                "stability": operation.get("x-stability", "Unknown"),
                "deprecated": operation.get("deprecated", False),
                "item_path": item_path,
                "item_type": typed_item,
            }

    def parameter_type(self, field: Schema, *, facades: bool = False) -> str:
        if "$ref" in field and "enum" in self.models.schemas[ref_name(field)]:
            enum_values = self.models.schemas[ref_name(field)]["enum"]
            return f"Literal[{', '.join(repr(value) for value in enum_values)}] | models.{ref_name(field)}"
        if facades:
            field = {key: value for key, value in field.items() if key in {"type", "$ref", "items", "enum", "oneOf", "anyOf"}}
        field_type = self.models.type_of(field, "Parameter", params=True)
        return field_type.replace("list[", "Sequence[") if facades else field_type

    def render(self) -> str:
        imports = '''"""Exact OpenAPI operations and their typed parameter models."""

from __future__ import annotations

from typing import Annotated, Literal, cast

from pydantic import Field

from . import models
from ._contracts import Operation, Parameter
from ._model import RequestParams
'''
        sections = [HEADER + imports.rstrip()]
        for op_id, entry in self.entries.items():
            params_name = entry["params"]
            fields = [f"class {params_name}(RequestParams):"]
            for param in entry["parameters"]:
                wire_key = param["name"]
                attr = field_name(wire_key)
                annotation = self.parameter_type(param["schema"])
                arguments = [] if param.get("required") else ["default=None"]
                if wire_key != attr:
                    arguments.append(f"alias={wire_key!r}")
                if not param.get("required"):
                    annotation = union([annotation, "None"])
                suffix = f" = Field({', '.join(arguments)})" if arguments else ""
                fields.append(f"    {attr}: {annotation}{suffix}")
            if len(fields) == 1:
                fields.append("    pass")
            sections.append("\n".join(fields))
            response = f'models.{entry["response"]}' if entry["media"] != "text/csv" else "str"
            response_expr = response
            if entry["response"] in self.models.aliases:
                response_expr = f"cast('type[{response}]', {response})"
            lines = [
                f'{entry["reference"]}: Operation[{params_name}, {response}] = Operation(',
                f"    id={op_id!r},",
                f'    path={entry["path"]!r},',
                f"    params={params_name},",
                f"    response={response_expr},",
                "    parameters=(",
            ]
            for param in entry["parameters"]:
                schema = resolve(self.models.schemas, param["schema"])
                choices = tuple(schema.get("enum", []))
                lines.append(
                    f"        Parameter({param['name']!r}, {param['in']!r}, {param.get('required', False)!r}, "
                    f"{choices!r}, {param.get('style')!r}, {param.get('explode', True)!r}),"
                )
            lines.append("    ),")
            for key in ("access", "cache_ttl", "paginated", "summary", "stability", "deprecated"):
                lines.append(f"    {key}={entry[key]!r},")
            lines.append(f'    media_type={entry["media"]!r},')
            lines.append(f'    item_field={entry["item_path"]!r},')
            item_type = entry["item_type"]
            item = f"models.{item_type}" if item_type in self.models.schemas or item_type in self.models.aliases or item_type in self.models.classes else item_type
            lines.append(f"    item_type={item},")
            lines.append(")")
            sections.append("\n".join(lines))
        lookup = ["OPERATIONS: dict[str, Operation[RequestParams, object]] = {"]
        lookup += [f"    {key!r}: {entry['reference']}," for key, entry in self.entries.items()]
        lookup.append("}")
        sections.append("\n".join(lookup))
        return "\n\n\n".join(sections) + "\n"


def routing_source(v1: Schema, overrides: Schema, snapshots: list[dict[str, Schema]]) -> str:
    domain_entries = {
        tuple(key.split("/")): (value["domain"], value["parameter"], value["query"])
        for key, value in overrides["id_domains"].items()
    }
    force_direct = [tuple(key.split("/")) for key in overrides["force_direct"]]
    catalog = [(resource, name) for resource, names in v1["resources"].items() for name in names]
    enum_legacy: set[tuple[str, str]] = set()
    for schemas in snapshots:
        for resource in v1["resources"]:
            schema = schemas.get(f"{pascal(resource)}SelectionName", {})
            for branch in schema.get("oneOf", []) + [schema]:
                description = branch.get("description", "")
                match = re.search(r"fall\s*back to API v1[^:]*:([^\n.]+)", description, re.I)
                if match:
                    enum_legacy.update((resource, name) for name in re.findall(r"'(\w+)'", match[1]))
    lines = [HEADER + '"""Routing declarations from the shared SDK contract."""']
    lines.append("\nID_DOMAINS = {")
    lines.extend(f"    {key!r}: {value!r}," for key, value in sorted(domain_entries.items()))
    lines.append("}")
    for name, values in (("FORCE_DIRECT", force_direct), ("V1_CATALOG", catalog), ("V2_ENUM_LEGACY", enum_legacy)):
        lines.append(f"\n{name} = frozenset((")
        lines.extend(f"    {value!r}," for value in sorted(values))
        lines.append("))")
    return "\n".join(lines) + "\n"


class Selections:
    def __init__(self, capabilities: list[Schema], overrides: Schema, ops: Operations, v1: Schema):
        self.ops = ops
        self.groups: dict[str, dict[str, Schema]] = defaultdict(dict)
        compat_types = overrides["compatibility_types"]
        for entry in capabilities:
            resource, name = entry["resource"], entry["name"]
            compatibility = compat_types.get(f"{resource}/{name}")
            endpoints = [ops.entries[ep["id"]] for ep in entry["endpoints"] or ()]
            expressions = [f'models.{ep["response"]}' for ep in endpoints if ep["media"] != "text/csv"]
            if any(ep["media"] == "text/csv" for ep in endpoints):
                expressions.append("str")
            if not expressions and compatibility:
                expressions.append(f"compatibility.{compatibility}")
            if not expressions:
                expressions.append("JsonValue")
            access_levels = ("public", "minimal", "limited", "full", "custom")
            access = min((ep["access"] for ep in endpoints), default="public", key=access_levels.index)
            self.groups[resource][name] = {
                **entry,
                "endpoints": entry["endpoints"] or [],
                "type": union(expressions),
                "result_type": union([*expressions, *([f"compatibility.{compatibility}"] if compatibility else [])]),
                "compat": f"compatibility.{compatibility}" if compatibility else None,
                "access": access,
            }
        for resource, names in v1["resources"].items():
            for name in names:
                self.groups[resource].setdefault(
                    name,
                    {
                        "resource": resource, "name": name, "type": "JsonValue", "result_type": "JsonValue", "compat": None,
                        "access": "public", "endpoints": [], "generic": False,
                        "standalone": False, "legacy": True, "csv": False,
                    },
                )
        self.deprecated = overrides["deprecated_aliases"]

    @staticmethod
    def namespace(resource: str) -> str:
        return f"{pascal(resource)}Selections"

    def render(self) -> str:
        imports = '''"""Typed selection tokens, grouped by Torn API resource."""

from __future__ import annotations

from typing import cast

from pydantic import JsonValue

from . import compatibility, models
from ._contracts import Endpoint, Selection
'''
        sections = [HEADER + imports.rstrip()]
        namespaces = ["SELECTIONS: dict[tuple[str, str], Selection[object]] = {"]
        for resource, entries in self.groups.items():
            namespace = self.namespace(resource)
            fields = [f"class {namespace}:"]
            for name, entry in entries.items():
                attr = field_name(name)
                response = entry["type"]
                result_type = entry["result_type"]
                response_expr = response
                if (
                    " | " in response
                    or response == "JsonValue"
                    or response.removeprefix("models.") in self.ops.models.aliases
                ):
                    response_expr = f"cast('type[{response}]', {response})"
                fields.extend([
                    f"    {attr}: Selection[{result_type}] = Selection(",
                    f"        resource={resource!r}, name={name!r},",
                    f"        response={response_expr},",
                    f"        legacy_response={entry['compat']},",
                    f"        access={entry['access']!r},",
                    "        endpoints=(",
                ])
                for endpoint in entry["endpoints"]:
                    fields.append(
                        f"            Endpoint({endpoint['id']!r}, {endpoint['path']!r}, "
                        f"{tuple(p for p in endpoint['parameters'] if p != 'key')!r}, "
                        f"{tuple(endpoint['required'] or ())!r}, {endpoint.get('schema')!r}),"
                    )
                fields.append("        ),")
                for key in ("generic", "standalone", "legacy", "csv"):
                    fields.append(f"        {key}={entry[key]},")
                fields.extend(["    )", ""])
                namespaces.append(f"    ({resource!r}, {name!r}): {resource}.{attr},")
            for qualified, alias in self.deprecated.items():
                ns, name = qualified.split("/")
                if ns == resource:
                    fields.append(f"    {field_name(name)} = {field_name(alias['selection'])}")
                    namespaces.append(f"    ({resource!r}, {name!r}): {resource}.{field_name(name)},")
            sections.append("\n".join(fields).rstrip())
            sections.append(f"{resource} = {namespace}()")
        namespaces.append("}")
        sections.append("\n".join(namespaces))
        return "\n\n\n".join(sections) + "\n"

    def filters(self, entry: Schema) -> dict[str, list[str]]:
        filters: dict[str, list[str]] = defaultdict(list)
        for endpoint in entry["endpoints"]:
            for parameter in self.ops.entries[endpoint["id"]]["parameters"]:
                key = parameter["name"]
                if parameter["in"] != "query" or key in {"id", "selections", "legacy"}:
                    continue
                annotation = self.ops.parameter_type(parameter["schema"], facades=True)
                if annotation not in filters[key]:
                    filters[key].append(annotation)
        return filters

    def resource_call(
        self, entry: Schema, *, asynchronous: bool, raw: bool, filters: dict[str, list[str]]
    ) -> list[str]:
        define = "async def" if asynchronous else "def"
        wait = "await " if asynchronous else ""
        resource = entry["resource"]
        name = entry["name"]
        attr = field_name(name)
        if raw:
            attr += "_raw"
        elif attr in {"select", "batch", "execute", "plan", "raw"}:
            attr += "_"
        response = ("str" if entry["csv"] else "dict[str, JsonValue]") if raw else entry["result_type"]
        lines = [f"    {define} {attr}(", "        self,", "        *,"]
        lines.extend(
            f"        {field_name(key)}: {union([*values, 'None'])} = None,"
            for key, values in filters.items()
        )
        lines.extend([
            "        query: Query | None = None,",
            "        path_args: Mapping[str, TargetValue] | None = None,",
            '        version: Version = "auto",',
            "        options: RequestOptions | None = None,",
        ])
        if not raw:
            lines.append("        strict: bool | None = None,")
        lines.append(f"    ) -> {response}:")
        if filters:
            lines.append("        extra_filters: dict[str, QueryValue] = {}")
            for key in filters:
                variable = field_name(key)
                lines.extend([
                    f"        if {variable} is not None:",
                    f"            extra_filters[{key!r}] = {variable}",
                ])
        source = "merge_filters(query, extra_filters)" if filters else "query"
        returns = f"cast({response!r}, {wait}self._raw_selected(" if raw else f"{wait}self.select("
        lines.extend([
            f"        return {returns}",
            f"            selections.{resource}.{field_name(name)}, query={source},",
            "            path_args=path_args, version=version, options=options,"
            + ("" if raw else " strict=strict,"),
            "        ))" if raw else "        )",
            "",
        ])
        return lines

    def award_calls(self, *, asynchronous: bool) -> list[str]:
        define = "async def" if asynchronous else "def"
        wait = "await " if asynchronous else ""
        lines: list[str] = []
        for name in ("honors", "medals"):
            prefix = f"User{pascal(name)}"
            cat_name = f"{prefix}Category"
            categories = self.ops.models.schemas[cat_name]["enum"]
            detail_types = ", ".join(repr(category) for category in categories if category != "all")
            for basic in (True, False):
                variant = "basic" if basic else "detailed"
                response = f"models.{prefix}{'' if basic else 'Detailed'}Response"
                lines.extend([f"    {define} {name}_{variant}(", "        self,"])
                if not basic:
                    lines.append(f"        category: Literal[{detail_types}] | models.{cat_name},")
                lines.extend([
                    "        *,",
                    "        query: Query | None = None,",
                    "        comment: str | None = None,",
                    "        timestamp: int | str | None = None,",
                    "        options: RequestOptions | None = None,",
                    "        strict: bool | None = None,",
                    f"    ) -> {response}:",
                    f'        """Return the {variant} {name} model for the key owner."""',
                ])
                if not basic:
                    lines.extend([
                        "        if category == 'all':",
                        f"            raise ValidationError('Use {name}_basic() for category all')",
                    ])
                category = "'all'" if basic else "category"
                lines.extend([
                    f"        filters: dict[str, QueryValue] = {{'cat': {category}}}",
                    "        if comment is not None:",
                    "            filters['comment'] = comment",
                    "        if timestamp is not None:",
                    "            filters['timestamp'] = timestamp",
                    f"        batch = {wait}self.batch(",
                    f"            selections.user.{name}, query=merge_filters(query, filters),",
                    "            options=options, force_direct=True, typed=False,",
                    "        )",
                    f"        payload = self._raw_value(batch, selections.user.{name})",
                    "        return decode(",
                    f"            self._client, {response}, payload, 'user.{name}', options,",
                    "            self._client.strict if strict is None else strict,",
                    "        )",
                    "",
                ])
        return lines

    def resources(self) -> str:
        imports = '''"""Typed calls on bound Torn API resources."""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from typing import Annotated, Literal, cast

from pydantic import Field, JsonValue

from . import compatibility, models, selections
from ._client_support import decode
from ._resource import AsyncResource, Resource, merge_filters
from .errors import ValidationError
from .planner import TargetValue, Version
from .runtime import Query, QueryValue, RequestOptions
'''
        sections = [HEADER + imports.rstrip()]
        for asynchronous in (False, True):
            prefix = "Async" if asynchronous else ""
            for resource, entries in self.groups.items():
                resource_class = f"{prefix}{pascal(resource)}"
                fields = [f"class {resource_class}({prefix}Resource):", f"    resource = {resource!r}", ""]
                for entry in entries.values():
                    filters = self.filters(entry)
                    for raw in (False, True):
                        fields.extend(self.resource_call(entry, asynchronous=asynchronous, raw=raw, filters=filters))
                if resource == "user":
                    fields.extend(self.award_calls(asynchronous=asynchronous))
                for qualified, alias in self.deprecated.items():
                    ns, name = qualified.split("/")
                    if ns == resource:
                        old, current = field_name(name), field_name(alias['selection'])
                        fields.extend([f"    {old} = {current}", f"    {old}_raw = {current}_raw"])
                sections.append("\n".join(fields).rstrip())
        return "\n\n\n".join(sections) + "\n"


def exact_calls(operations: Operations) -> str:
    imports = '''"""Typed sync and async convenience methods for every OpenAPI operation."""

from __future__ import annotations

from abc import ABC, abstractmethod
from collections.abc import AsyncIterator, Iterator
from typing import TypeVar, cast

from . import models, operations
from ._contracts import Operation
from ._model import RequestParams
from .runtime import Query, RequestOptions

P = TypeVar("P", bound=RequestParams)
R = TypeVar("R")
'''
    sections = [HEADER + imports.rstrip()]
    for asynchronous in (False, True):
        prefix = "Async" if asynchronous else ""
        wait = "await " if asynchronous else ""
        iterator = f"{prefix}Iterator"
        name = f"{prefix}ExactCalls"
        lines = [f"class {name}(ABC):"]
        for kind in ("exact", "exact_pages", "exact_items"):
            define = "async def" if asynchronous and kind == "exact" else "def"
            returns = {"exact": "R", "exact_pages": f"{iterator}[R]", "exact_items": f"{iterator}[object]"}[kind]
            lines.extend([
                "    @abstractmethod",
                f"    {define} {kind}(",
                "        self,",
                "        operation: Operation[P, R],",
                "        params: P | None = None,",
                "        *,",
                "        query: Query | None = None,",
                "        options: RequestOptions | None = None,",
                "        strict: bool | None = None,",
            ])
            if kind != "exact":
                lines.extend([
                    "        backwards: bool = False,",
                    "        max_pages: int | None = None,",
                ])
            if kind == "exact_items":
                lines.append("        limit: int | None = None,")
            lines.extend([f"    ) -> {returns}: ...", ""])
        for entry in operations.entries.values():
            reference = entry["reference"]
            response = f'models.{entry["response"]}' if entry["media"] != "text/csv" else "str"
            params = f"operations.{entry['params']}" + ("" if entry["required"] else " | None = None")
            for kind in ("exact", "exact_pages", "exact_items"):
                if kind != "exact" and (not entry["paginated"] or (kind == "exact_items" and not entry["item_type"])):
                    continue
                define = "async def" if asynchronous and kind == "exact" else "def"
                suffix = kind.removeprefix("exact")
                item = entry["item_type"]
                item_annotation = "object"
                if item:
                    item_annotation = f"models.{item}" if item in operations.models.schemas or item in operations.models.aliases or item in operations.models.classes else item
                returns = {"exact": response, "exact_pages": f"{iterator}[{response}]", "exact_items": f"{iterator}[{item_annotation}]"}[kind]
                lines.extend([
                    f"    {define} {reference}{suffix}(",
                    "        self,",
                    f"        params: {params},",
                    "        *,",
                    "        query: Query | None = None,",
                    "        options: RequestOptions | None = None,",
                    "        strict: bool | None = None,",
                ])
                if kind != "exact":
                    lines.extend([
                        "        backwards: bool = False,",
                        "        max_pages: int | None = None,",
                    ])
                if kind == "exact_items":
                    lines.append("        limit: int | None = None,")
                lines.append(f"    ) -> {returns}:")
                head = f"{wait}self.{kind}" if kind == "exact" else f"self.{kind}"
                args = f"operations.{reference}, params, query=query, options=options, strict=strict"
                if kind != "exact":
                    args += ", backwards=backwards, max_pages=max_pages"
                if kind == "exact_items":
                    args += ", limit=limit"
                call = f"{head}({args})"
                if kind == "exact_items":
                    call = f"cast({returns!r}, {call})"
                lines.extend([f"        return {call}", ""])
        sections.append("\n".join(lines).rstrip())
    return "\n\n\n".join(sections) + "\n"


def generate() -> dict[Path, str]:
    provenance = read("provenance.json")
    latest = provenance["snapshots"][0]
    inputs = (ROOT / latest["file"]).read_bytes()
    model_spec = json.loads(inputs)
    for snapshot in provenance["snapshots"]:
        raw = (ROOT / snapshot["file"]).read_bytes()
        if hashlib.sha256(raw).hexdigest() != snapshot["sha256"]:
            raise ValueError(f"Official input digest mismatch for {snapshot['file']}")
    overrides = {
        (entry["schema"], entry["property"]): entry["change"]
        for entry in read("shared/spec-overrides.json")["overrides"]
    }
    routing_overrides = read("routing-overrides.json")
    v1 = read("v1-catalog.json")
    schemas = model_spec["components"]["schemas"]
    models = Models(schemas, overrides)
    models.populate()
    compat = Compatibility(read("compatibility-models.json"), {})
    compat.populate()
    access = read("shared/access-levels.json")["operations"]
    operations = Operations(model_spec, models, access)
    selections = Selections(read("routing-manifest.json")["capabilities"], routing_overrides, operations, v1)
    archived = {
        snapshot["version"]: read(snapshot["file"].removeprefix("spec/"))["components"]["schemas"]
        for snapshot in provenance["snapshots"][1:]
    }
    routing = routing_source(v1, routing_overrides, [schemas, *archived.values()])
    generated = {
        PACKAGE / "models.py": models.render(f"Torn OpenAPI {latest['version']} response schemas."),
        PACKAGE / "operations.py": operations.render(),
        PACKAGE / "selections.py": selections.render(),
        PACKAGE / "_routing.py": routing,
        PACKAGE / "_generated_calls.py": exact_calls(operations),
        PACKAGE / "_generated_resources.py": selections.resources(),
        PACKAGE / "compatibility.py": compat.render(
            "Historical SDK convenience and legacy response models.",
            """from __future__ import annotations

from typing import Annotated, TypeAlias

from pydantic import AliasChoices, BeforeValidator, Field, JsonValue

from ._compat_model import CompatibilityModel, company_news, position_name, stringish
from ._model import WireModel
from .models import ReviveSetting, UserDonatorStatusEnum
""",
        ),
        PACKAGE / "_spec.py": HEADER + f'''"""Version and provenance for the embedded OpenAPI contract."""

SPEC_VERSION = {latest["version"]!r}
SPEC_SHA256 = {latest["sha256"]!r}
OPERATION_COUNT = {len(operations.entries)}
SCHEMA_COUNT = {len(schemas)}
''',
    }
    historical = PACKAGE / "historical"
    modules = []
    for version, archive in archived.items():
        version_models = Models(archive, overrides)
        version_models.populate()
        name = "v" + version.replace(".", "_")
        modules.append(name)
        generated[historical / f"{name}.py"] = version_models.render(
            f"Frozen Torn OpenAPI {version} response schemas.",
            MODEL_IMPORTS.replace("from ._model", "from .._model"),
        )
    generated[historical / "__init__.py"] = (
        HEADER + '"""Frozen OpenAPI models, organized by spec version."""\n\n'
        f"__all__ = {modules!r}\n"
    )
    return generated


def main() -> int:
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("--check", action="store_true", help="fail if generated files differ")
    args = cli.parse_args()
    changed: list[Path] = []
    for path, output in generate().items():
        data = output.encode("utf-8")
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                changed.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    for path in changed:
        print(f"Generated file has drifted: {path}")
    return int(bool(changed))


if __name__ == "__main__":
    raise SystemExit(main())
